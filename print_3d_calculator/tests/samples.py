def bgcode():
    def block(block_type, payload, compression=0):
        if compression == 1:
            compressed = zlib.compress(payload)
            header = struct.pack('<HHII', block_type, 1, len(payload), len(compressed))
            payload = compressed
        else:
            header = struct.pack('<HHI', block_type, 0, len(payload))
        return header + struct.pack('<H', 0) + payload + b'\0\0\0\0'

    file_meta = b'Producer=PrusaSlicer 2.7.1\n'
    printer_meta = (
        b'printer_model=MK4\nfilament_type=PLA;PETG\nextruder_colour=#FF8000;#000000\n'
        b'filament used [mm]=1000.00,500.00\nfilament used [g]=3.00,1.60\n'
        b'estimated printing time (normal mode)=2h 30m 0s\n'
    )
    print_meta = b'filament used [g]=3.00,1.60\nestimated printing time (normal mode)=2h 30m 0s\n'
    gcode = b'G1 X1 Y1 E1\n'
    return (
        b'GCDE' + struct.pack('<IH', 1, 1)
        + block(0, file_meta) + block(3, printer_meta) + block(4, print_meta, compression=1)
        + block(1, gcode)
    )


