def cube_triangles(size=10.0, offset=(0.0, 0.0, 0.0)):
    """12 outward-facing triangles of an axis-aligned cube."""
    ox, oy, oz = offset
    s = size
    v = [
        (ox, oy, oz), (ox + s, oy, oz), (ox + s, oy + s, oz), (ox, oy + s, oz),
        (ox, oy, oz + s), (ox + s, oy, oz + s), (ox + s, oy + s, oz + s), (ox, oy + s, oz + s),
    ]
    faces = [
        (0, 2, 1), (0, 3, 2),  # bottom
        (4, 5, 6), (4, 6, 7),  # top
        (0, 1, 5), (0, 5, 4),  # front
        (2, 3, 7), (2, 7, 6),  # back
        (1, 2, 6), (1, 6, 5),  # right
        (0, 4, 7), (0, 7, 3),  # left
    ]
    return v, faces


def stl_binary(size=10.0):
    vertices, faces = cube_triangles(size)
    out = io.BytesIO()
    out.write(b'\0' * 80)
    out.write(struct.pack('<I', len(faces)))
    for a, b, c in faces:
        out.write(struct.pack('<3f', 0, 0, 0))
        for index in (a, b, c):
            out.write(struct.pack('<3f', *vertices[index]))
        out.write(b'\0\0')
    return out.getvalue()


def stl_ascii(size=10.0):
    vertices, faces = cube_triangles(size)
    lines = ['solid cube']
    for face in faces:
        lines += ['  facet normal 0 0 0', '    outer loop']
        lines += ['      vertex %f %f %f' % vertices[i] for i in face]
        lines += ['    endloop', '  endfacet']
    lines.append('endsolid cube')
    return '\n'.join(lines).encode()


def obj_two_materials(size=10.0):
    v1, faces = cube_triangles(size)
    v2, _ = cube_triangles(size, offset=(20.0, 0.0, 0.0))
    lines = ['v %f %f %f' % p for p in v1 + v2]
    lines.append('usemtl Red')
    lines += ['f %d %d %d' % (a + 1, b + 1, c + 1) for a, b, c in faces]
    lines.append('usemtl Blue')
    lines += ['f %d %d %d' % (a + 9, b + 9, c + 9) for a, b, c in faces]
    return '\n'.join(lines).encode()


def amf_cube(size=10.0):
    vertices, faces = cube_triangles(size)
    parts = ['<?xml version="1.0" encoding="UTF-8"?>', '<amf unit="millimeter">', '<object id="0"><mesh><vertices>']
    for x, y, z in vertices:
        parts.append('<vertex><coordinates><x>%s</x><y>%s</y><z>%s</z></coordinates></vertex>' % (x, y, z))
    parts.append('</vertices><volume materialid="1">')
    for a, b, c in faces:
        parts.append('<triangle><v1>%d</v1><v2>%d</v2><v3>%d</v3></triangle>' % (a, b, c))
    parts.append('</volume></mesh></object></amf>')
    return ''.join(parts).encode()


def model_xml(size=20.0, unit='millimeter', application='PrusaSlicer-2.7.1'):
    vertices, faces = cube_triangles(size)
    parts = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<model unit="%s" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">' % unit,
        '<metadata name="Application">%s</metadata>' % application,
        '<resources><object id="1" type="model"><mesh><vertices>',
    ]
    parts += ['<vertex x="%s" y="%s" z="%s"/>' % p for p in vertices]
    parts.append('</vertices><triangles>')
    parts += ['<triangle v1="%d" v2="%d" v3="%d"/>' % f for f in faces]
    parts.append('</triangles></mesh></object></resources>')
    parts.append('<build><item objectid="1" transform="1 0 0 0 1 0 0 0 1 50 50 0"/></build></model>')
    return ''.join(parts).encode()


