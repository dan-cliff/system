// Regenerates static/src/live/world_data.js (run outside Odoo, needs Node):
//   npm install world-atlas@2.0.2 topojson-client@3.1.0 d3-geo@3.1.1 world-countries@5.1.0
//   node build_world_data.mjs 1.0 ../static/src/live/world_data.js
import fs from 'fs';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';
const land = feature(JSON.parse(fs.readFileSync('node_modules/world-atlas/land-50m.json')), 'land');
const countries = JSON.parse(fs.readFileSync('node_modules/world-countries/countries.json'));
const STEP = parseFloat(process.argv[2] || '1.4');
const dots = [];
for (let lat = 83; lat >= -56; lat -= STEP) {
  const lngStep = STEP / Math.max(Math.cos(lat * Math.PI / 180), 0.2);
  for (let lng = -180 + lngStep / 2; lng < 180; lng += lngStep) {
    if (geoContains(land, [lng, lat])) dots.push(Math.round(lat * 10), Math.round(lng * 10));
  }
}
const centroids = {};
for (const c of countries) if (c.latlng && c.latlng.length === 2) centroids[c.cca2] = [Math.round(c.latlng[0] * 10) / 10, Math.round(c.latlng[1] * 10) / 10];
const out = `/* Generated by live_sales_counter/tools/build_world_data.mjs (world-atlas land-50m, world-countries).
 * dots: flat list of [lat*10, lng*10] pairs on an equal-area grid of land.
 * centroids: ISO 3166-1 alpha-2 code -> [lat, lng], used when a buyer's city
 * has not been geocoded yet. */
window.LSC_WORLD = ${JSON.stringify({ dots, centroids })};
`;
fs.writeFileSync(process.argv[3], out);
console.log(dots.length / 2, 'dots', Object.keys(centroids).length, 'countries', out.length, 'bytes');
